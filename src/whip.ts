/** The frames side by side as one SVG: one path per colour, one rect per run of pixels. */
export function spriteSheet(frames: readonly (readonly string[])[] = FRAMES): string {
  const runs: Record<string, string[]> = {};
  frames.forEach((rows, f) =>
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; ) {
        const colour = row[x];
        let end = x + 1;
        while (row[end] === colour) end++;
        if (colour !== '.') (runs[colour] ??= []).push(`M${f * FRAME_W + x} ${y}h${end - x}v1h${x - end}z`);
        x = end;
      }
    }),
  );
  const width = frames.length * FRAME_W;
  const paths = Object.entries(runs)
    .map(([colour, d]) => `<path fill="${PALETTE[colour]}" d="${d.join('')}"/>`)
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${FRAME_H}" shape-rendering="crispEdges">${paths}</svg>`;
}

/** CSS background-image value: inline, so it travels into the floating window and works offline. */
export function spriteUrl(): string {
  return `url("data:image/svg+xml,${encodeURIComponent(spriteSheet())}")`;
}
